// Regenerates preview.html from the SVGs in this folder (and the heraldry glyphs): node build-preview.mjs
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const read = (dir, f) => readFileSync(join(dir, f), 'utf8').trim();
const heraldry = join(here, '..', 'heraldry');
const files = readdirSync(here).filter((f) => f.endsWith('.svg') && f !== 'logo-legatum.svg').sort();
const glyphs = readdirSync(heraldry).filter((f) => f.startsWith('glyph-') && f.endsWith('.svg')).sort();
const items = [...files.map((f) => ({ name: f.slice(0, -4), svg: read(here, f) })), ...glyphs.map((f) => ({ name: f.slice(0, -4), svg: read(heraldry, f) }))];

const SECTIONS = [
  ['Units', (n) => n.startsWith('unit-')],
  ['Buildings (every tier, and the faction pieces that replace one)', (n) => n.startsWith('building-')],
  ['Yields', (n) => n.startsWith('yield-')],
  ['Resources', (n) => n.startsWith('resource-')],
  ['Titles', (n) => n.startsWith('title-')],
  ['Milestones', (n) => n.startsWith('milestone-')],
  ['Interface (replace text glyphs)', (n) => n.startsWith('ui-')],
  ['Map order badges', (n) => n.startsWith('mark-')],
  ['Faction glyphs (heraldry, 16 to 24 px)', (n) => n.startsWith('glyph-')],
  ['Map and misc', () => true],
];
const TINTS = ['#e0a84a', '#63c2d6', '#e07a64', '#a79bea'];
const cell = (i) => `<div class="cell"><div class="big" style="color:#ece6d6">${i.svg}</div><div class="tints">${TINTS.map((c) => `<span style="color:${c}">${i.svg}</span>`).join('')}</div><div class="tiny"><span class="s16" style="color:#ece6d6">${i.svg}</span><span class="s24" style="color:#ece6d6">${i.svg}</span><span class="s16 paper" style="color:#2b2a26">${i.svg}</span></div><div class="label">${i.name}</div></div>`;
const left = new Set(items.map((i) => i.name));
const sections = SECTIONS.map(([title, test]) => {
  const mine = items.filter((i) => left.has(i.name) && test(i.name));
  mine.forEach((i) => left.delete(i.name));
  return mine.length ? `<h2>${title}</h2><div class="grid">${mine.map(cell).join('')}</div>` : '';
}).join('\n');
const logo = read(here, 'logo-legatum.svg');

writeFileSync(join(here, 'preview.html'), `<!doctype html>
<html lang="en"><head><meta charset="utf-8"><title>Legatum Icons</title><style>
  * { box-sizing: border-box; margin: 0; }
  body { background: #0b0e12; font: 12px/1.3 ui-monospace, Menlo, monospace; padding: 24px; }
  .panel { background: #11151b; color: #e9e5d9; border-radius: 14px; padding: 28px 32px 32px; }
  header { display: flex; align-items: flex-end; justify-content: space-between; border-bottom: 1px solid #262d38; padding-bottom: 18px; }
  .logo svg { height: 40px; width: auto; display: block; }
  .meta { color: #7d8595; letter-spacing: .08em; text-transform: uppercase; font-size: 11px; }
  h2 { font-size: 11px; font-weight: 600; color: #7d8595; letter-spacing: .16em; text-transform: uppercase; margin: 22px 0 10px; }
  .grid { display: grid; grid-template-columns: repeat(8, 1fr); gap: 10px; }
  .cell { background: #181d25; border: 1px solid #262d38; border-radius: 10px; padding: 14px 10px 10px; display: flex; flex-direction: column; align-items: center; gap: 10px; }
  .big svg { width: 48px; height: 48px; display: block; }
  .tints { display: flex; gap: 8px; }
  .tints svg { width: 24px; height: 24px; display: block; }
  .tiny { display: flex; gap: 10px; align-items: center; }
  .s16 svg { width: 16px; height: 16px; display: block; }
  .s24 svg { width: 24px; height: 24px; display: block; }
  .paper { background: #efe6d0; padding: 3px; border-radius: 3px; }
  .label { color: #7d8595; font-size: 10.5px; text-align: center; word-break: break-all; }
</style></head>
<body>
  <section class="panel">
    <header>
      <div class="logo" style="color:#e9e5d9">${logo}</div>
      <div class="meta">Icon set &middot; solid silhouettes &middot; 24&times;24 grid, currentColor &middot; generated by build-preview.mjs</div>
    </header>
${sections}
  </section>
</body></html>
`);
console.log(`preview.html: ${items.length} icons`);
