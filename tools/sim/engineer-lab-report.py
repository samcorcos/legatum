#!/usr/bin/env python3
"""Tables for the Military Engineer lab: can a walled city be taken, with and without Engineers?

  engineer-lab-report.py CELLS.csv[.gz] [--summary summary.json] [--out DIR] [--price N]

Writes DIR/results.md. Standard library only.

Terms.
  cell       one starting situation (army, city, garrison, era, faction), played once per dice
             seed (`runs`, 32 by default). Every policy within a seed faces the same dice.
  wall tier  0 no Walls, 1 Walls, 2 a Castle, 3 a Star Fort (the `walls` column).
  eng tier   the siege tier of the attacker's Engineers: 1 Mathematics (Catapult), 2 Machinery
             (Trebuchet), 3 Metallurgy (Bombard).
  mix        melee: all melee. mixed: half melee, half archers. shooters: one melee, the rest
             archers.
  policy     storm: every melee unit walks in every turn. wait: shooters first, melee commits at
             half HP. "Best forced" is the better of the two by capture rate, cell by cell.
  capture    share of the dice seeds where the city falls.

Variants.
  base            no Engineer: Walls halve every attack on the city's HP
  stacked         one Engineer per fighting unit, on that unit's tile
  adjacent        one Engineer per four units, covering the units next to it
  *_p25 / p75 / p100   the same, where an Engineer below the walls' tier gives back 25 / 75 / 100
                  percent of the damage (the default is 50)

Production figures use the price in the file (60); `--price N` re-prices the Engineers.
"""
import argparse
import csv
import gzip
import json
from pathlib import Path

STRINGS = {"cell", "era", "faction", "mix", "garrison_type", "ground", "variant"}
METRICS = ("capture", "turns", "att_lost", "def_lost", "loss_cost", "breach", "breach_turns",
           "city_dmg", "eng_lost", "def_cost")
FILE_PRICE = 60
MIXES = ("melee", "mixed", "shooters")
ERAS = ("ancient", "classical", "renaissance")


def load(path):
    opener = gzip.open if str(path).endswith(".gz") else open
    with opener(path, "rt", newline="") as fh:
        rows = list(csv.DictReader(fh))
    for r in rows:
        for k, v in list(r.items()):
            if k is None or k in STRINGS:
                continue
            if v in (None, ""):
                r[k] = None
            else:
                try:
                    r[k] = float(v)
                except ValueError:
                    pass
    return rows


def sel(rows, **conds):
    return [r for r in rows if all(r.get(k) == v for k, v in conds.items())]


def avg(xs):
    xs = [x for x in xs if x is not None]
    return sum(xs) / len(xs) if xs else None


def best_forced(r, price):
    forced = [p for p in ("storm", "wait") if r.get(f"{p}_capture") is not None]
    if not forced:
        return None
    p = max(forced, key=lambda q: (r[f"{q}_capture"], q == "storm"))
    rec = {m: r.get(f"{p}_{m}") for m in METRICS}
    n = r.get("eng_n") or 0
    rec["eng_n"] = n
    rec["army_cost"] = (r.get("army_cost") or 0) + n * (price - FILE_PRICE)
    # Engineers that were captured count as lost at the price.
    rec["loss_cost"] = (rec["loss_cost"] or 0) + (rec["eng_lost"] or 0) * price
    return rec


def pool(rows, price):
    recs = [x for x in (best_forced(r, price) for r in rows) if x]
    if not recs:
        return None
    out = {"cells": len(recs)}
    for m in METRICS + ("army_cost", "eng_n"):
        out[m] = avg([x[m] for x in recs])
    cap = out["capture"]
    out["cost_per_capture"] = out["army_cost"] / cap if cap else None
    out["loss_per_capture"] = out["loss_cost"] / cap if cap else None
    return out


def pct(x):
    return "-" if x is None else f"{100 * x:.0f}%"


def whole(x):
    return "-" if x is None else f"{x:.0f}"


def tenth(x):
    return "-" if x is None else f"{x:.1f}"


def md(headers, body):
    out = ["| " + " | ".join(str(h) for h in headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    out += ["| " + " | ".join(str(c) for c in row) + " |" for row in body]
    return "\n".join(out)


def variants_in(rows):
    order = ["base", "stacked", "adjacent", "stacked_p25", "stacked_p75", "stacked_p100",
             "adjacent_p75", "adjacent_p100"]
    found = {r.get("variant") for r in rows}
    return [v for v in order if v in found] + sorted(found - set(order))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("csv")
    ap.add_argument("--summary")
    ap.add_argument("--out", default=".")
    ap.add_argument("--price", type=int, default=FILE_PRICE)
    a = ap.parse_args()
    rows = load(a.csv)
    price = a.price
    summary = json.loads(Path(a.summary).read_text()) if a.summary else {}
    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    L = ["# Military Engineer lab\n"]
    L.append(f"Generated by `tools/sim/engineer-lab-report.py` from `{Path(a.csv).name}`. Terms and "
             "variants are in that script's docstring.\n")
    L.append(md(["", ""], [
        ["Cells", f"{int(summary.get('cells', len(rows))):,}"],
        ["Dice seeds per cell", int(summary.get("repeats", 0))],
        ["Fights", f"{int(summary.get('fights', 0)):,}"],
        ["Engineer price", price],
    ]))
    walled1 = [r for r in rows if r["walls"] == 1]
    eras = [e for e in ("classical", "renaissance") if any(r["era"] == e for r in rows)]
    plain = [v for v in variants_in(rows) if not v.endswith(("p25", "p75", "p100"))]

    L.append("\n## 1. Pooled: a walled city (Walls only), by variant\n")
    L.append("Every army size, mix, garrison and faction in the file; the Engineer's tier is "
             "the era's own, so Walls are always within its reach.\n")
    body = []
    for era in eras:
        for v in plain:
            s = pool(sel(walled1, era=era, variant=v), price)
            if s:
                body.append([era, v, s["cells"], whole(s["army_cost"]), pct(s["capture"]),
                             tenth(s["turns"]), whole(s["loss_cost"]), whole(s["loss_per_capture"]),
                             whole(s["cost_per_capture"]), tenth(s["eng_lost"]), pct(s["breach"])])
    L.append(md(["Era", "Variant", "Cells", "Army cost", "Capture", "Turns", "Production lost",
                 "Lost per capture", "Army cost per capture", "Engineers lost", "Breach"], body))

    L.append("\n## 2. The typical cell: four units, one shooter in the city\n")
    typical = [r for r in walled1 if r["n"] == 4 and r["garrison"] == 1 and r["garrison_type"] == "ranged"]
    body = []
    for era in eras:
        for mix in MIXES:
            line = [era, mix]
            for v in ("base", "stacked", "adjacent"):
                s = pool(sel(typical, era=era, mix=mix, variant=v), price)
                line.append(pct(s["capture"]) if s else "-")
            for v in ("stacked", "adjacent", "base"):
                s = pool(sel(typical, era=era, mix=mix, variant=v), price)
                line.append(whole(s["army_cost"]) if s else "-")
            body.append(line)
    L.append(md(["Era", "Army", "No Engineer", "Stacked", "Adjacent", "Cost stacked", "Cost adjacent",
                 "Cost without"], body))

    L.append("\n## 3. By army size (Walls only, all garrisons)\n")
    body = []
    for era in eras:
        for n in (3, 4, 6):
            for mix in MIXES:
                if n == 2 and mix == "shooters":
                    continue
                line = [era, n, mix]
                for v in ("base", "stacked", "adjacent"):
                    s = pool(sel(walled1, era=era, n=n, mix=mix, variant=v), price)
                    line.append(pct(s["capture"]) if s else "-")
                body.append(line)
    L.append(md(["Era", "Units", "Army", "No Engineer", "Stacked", "Adjacent"], body))

    L.append("\n## 4. Open cities and the Ancient era (no Engineer exists yet)\n")
    body = []
    for era in ERAS:
        for mix in MIXES:
            op = pool(sel(rows, era=era, mix=mix, variant="base", walls=0), price)
            wa = pool(sel(rows, era=era, mix=mix, variant="base", walls=1), price)
            body.append([era, mix, pct(op["capture"]) if op else "-", pct(wa["capture"]) if wa else "-",
                         tenth(op["turns"]) if op else "-", tenth(wa["turns"]) if wa else "-"])
    L.append(md(["Era", "Army", "Capture, open", "Capture, Walls", "Turns, open", "Turns, Walls"], body))

    L.append("\n## 5. Higher walls: the Engineer's tier against the city's (Renaissance)\n")
    L.append("Capture rate of 4 and 6 unit melee and mixed armies (all garrisons) by the city's walls "
             "tier and the Engineer's siege tier. The `_p` variants set the damage percent an Engineer "
             "below the city's tier gives back (the default is 50; at the city's tier or above, a "
             "full cancel). Walls-only cities are played once, at the era's own tier (3).\n")
    ren = [r for r in rows if r["era"] == "renaissance" and r["mix"] in ("melee", "mixed") and r["n"] in (4, 6)]
    variants = [v for v in ("base", "stacked_p25", "stacked", "stacked_p75", "stacked_p100",
                            "adjacent", "adjacent_p75", "adjacent_p100") if any(r["variant"] == v for r in rows)]
    body = []
    for wall in (1, 2, 3):
        for tier in (0, 1, 2, 3):
            line = [wall, tier or "none"]
            have = False
            for v in variants:
                if v == "base":
                    s = pool(sel(ren, variant="base", walls=wall), price) if tier == 0 else None
                elif tier == 0:
                    s = None
                elif wall == 1:
                    s = pool(sel(ren, variant=v, walls=1), price) if tier == 3 else None
                else:
                    s = pool(sel(ren, variant=v, walls=wall, eng_tier=float(tier)), price)
                have = have or bool(s)
                line.append(pct(s["capture"]) if s else "-")
            if have:
                body.append(line)
    L.append(md(["Walls tier", "Engineer tier"] + variants, body))

    L.append("\n## 6. Engineers lost\n")
    body = []
    for v in variants_in(rows):
        if v == "base":
            continue
        s = pool(sel(walled1, variant=v), price)
        if s:
            body.append([v, tenth(s["eng_n"]), tenth(s["eng_lost"]),
                         pct((s["eng_lost"] or 0) / s["eng_n"]) if s["eng_n"] else "-"])
    L.append(md(["Variant", "Engineers fielded", "Lost or captured per fight", "Share"], body))
    (out / "results.md").write_text("\n".join(L) + "\n")
    print(f"wrote {out / 'results.md'}")


if __name__ == "__main__":
    main()
